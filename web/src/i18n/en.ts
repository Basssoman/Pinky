const WORDS = { day: ['day', 'days'], hour: ['hour', 'hours'], minute: ['minute', 'minutes'] } as const;
const say = (x: Span) => (x.n === 1 ? `1 ${WORDS[x.unit][0]}` : `${x.n} ${WORDS[x.unit][1]}`);
/** A duration in ms → "14 days", "5 hours", "20 minutes". */
const span = (ms: number) => say(spanOf(ms));

