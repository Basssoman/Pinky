type Case = 'nom' | 'acc' | 'gen';
// [one, few, many] for each case: 1 день / 2 дні / 5 днів; протягом 1 дня / 2 днів; через 1 годину.
const WORDS: Record<Unit, Record<Case, [string, string, string]>> = {
  day: { nom: ['день', 'дні', 'днів'], acc: ['день', 'дні', 'днів'], gen: ['дня', 'днів', 'днів'] },
  hour: { nom: ['година', 'години', 'годин'], acc: ['годину', 'години', 'годин'], gen: ['години', 'годин', 'годин'] },
  minute: { nom: ['хвилина', 'хвилини', 'хвилин'], acc: ['хвилину', 'хвилини', 'хвилин'], gen: ['хвилини', 'хвилин', 'хвилин'] },
};
const say = (x: Span, c: Case = 'nom') => {
  const [one, few, many] = WORDS[x.unit][c];
  return `${x.n} ${pluralForm('uk-UA', x.n, { one, few, many, other: few })}`;
};
