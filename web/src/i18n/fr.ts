const WORDS = { day: ['jour', 'jours'], hour: ['heure', 'heures'], minute: ['minute', 'minutes'] } as const;
const say = (x: Span) => (x.n <= 1 ? `${x.n} ${WORDS[x.unit][0]}` : `${x.n} ${WORDS[x.unit][1]}`);
const span = (ms: number) => say(spanOf(ms));
/** "le 20 novembre", but "l’échéance" stays as it is. */
const le = (d: string) => (/^\d/.test(d) ? `le ${d}` : d);
/** "jusqu’au 20 novembre" / "jusqu’à l’échéance". */
const jusqua = (d: string) => (/^\d/.test(d) ? `jusqu’au ${d}` : `jusqu’à ${d}`);

